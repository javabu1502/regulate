    func application(_ application: UIApplication, didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]?) -> Bool {
        // Claim the playback audio session.
        //
        // Two things depend on this. A meditation runs to four and a half
        // minutes, and without .playback the audio stops the moment the
        // screen locks, which is exactly when someone lying down with their
        // eyes shut wants it to carry on. And .playback ignores the ring and
        // silent switch, which on the web build silently mutes every Web
        // Audio sound in the app: the bowls, the beads, the tide, and the
        // ambient beds under the exercises.
        do {
            try AVAudioSession.sharedInstance().setCategory(.playback, mode: .spokenAudio, options: [])
            try AVAudioSession.sharedInstance().setActive(true)
        } catch {
            // Audio is not worth refusing to launch over.
        }
        return true
    }

